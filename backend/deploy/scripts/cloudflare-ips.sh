#!/usr/bin/env bash
# Run on the VPS with sudo after the API domain is behind the Cloudflare proxy.
# 1. Writes /etc/nginx/conf.d/cloudflare-real-ip.conf so nginx sees real visitor IPs.
# 2. Allows ports 80/443 in ufw ONLY from Cloudflare's IP ranges.
# Re-run occasionally — Cloudflare publishes its ranges at https://www.cloudflare.com/ips/
set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
  echo "Run with sudo." >&2
  exit 1
fi

V4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
V6="$(curl -fsS https://www.cloudflare.com/ips-v6)"

if [ -z "$V4" ] || [ -z "$V6" ]; then
  echo "Could not download Cloudflare IP ranges." >&2
  exit 1
fi

echo "==> Writing /etc/nginx/conf.d/cloudflare-real-ip.conf"
{
  echo "# Generated by cloudflare-ips.sh — do not edit by hand"
  for ip in $V4 $V6; do echo "set_real_ip_from $ip;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/conf.d/cloudflare-real-ip.conf

nginx -t
systemctl reload nginx

echo "==> Updating ufw: 80/443 only from Cloudflare"
# Remove any existing open-to-everyone web rules.
ufw delete allow 80/tcp  >/dev/null 2>&1 || true
ufw delete allow 443/tcp >/dev/null 2>&1 || true
ufw delete allow 'Nginx Full' >/dev/null 2>&1 || true
ufw delete allow 'Nginx HTTP' >/dev/null 2>&1 || true

for ip in $V4 $V6; do
  ufw allow proto tcp from "$ip" to any port 80,443 comment 'Cloudflare' >/dev/null
done

ufw status numbered
echo "==> Done."
